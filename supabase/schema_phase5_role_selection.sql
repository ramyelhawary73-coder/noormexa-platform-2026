-- ============================================================
-- المشكلة: تسجيل الدخول بجوجل كان بيعمل حساب "متسوق" افتراضيًا
-- من غير ما يسأل المستخدم هل هو بائع/متجر/معلن/متسوق فعليًا.
--
-- الحل: عمود جديد بيسجّل هل المستخدم اختار نوع حسابه فعليًا
-- (سواء وقت التسجيل بالإيميل، أو من صفحة اختيار مخصصة بعد جوجل).
-- ============================================================

alter table public.profiles
  add column if not exists account_type_chosen boolean not null default false;

-- أي حساب اتسجل قبل كده بالإيميل (عنده اسم متجر أو نوع غير متسوق)
-- نعتبره اختار نوعه فعليًا، عشان مايتعرضلوش شاشة الاختيار من غير داعي.
update public.profiles
set account_type_chosen = true
where account_type <> 'customer' or business_name is not null;
