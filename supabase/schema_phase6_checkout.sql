-- NOORMEXA — المرحلة 6: تفعيل الشراء الفعلي (Checkout)
-- ============================================================
-- الجداول orders و order_items كانت موجودة من قبل، لكن كان ناقص
-- صلاحية "الإضافة" (insert) على order_items، فكان أي محاولة شراء
-- فعلية هتفشل. شغّل الملف ده لتفعيل الشراء بالكامل.
-- ============================================================

drop policy if exists "order_items_buyer_insert" on public.order_items;
create policy "order_items_buyer_insert"
  on public.order_items for insert
  with check (
    order_id in (select id from public.orders where buyer_id = auth.uid())
  );

