// Helper: Generate dynamic rate quotes based on carriers
export function getShippingQuotes(
  originCountry: string,
  destCountry: string,
  weightKg = 1,
  speed: "standard" | "priority" | "same_day" = "standard"
): ShippingRateQuote[] {
  const isDomestic = originCountry.trim().toLowerCase() === destCountry.trim().toLowerCase();

  return INITIAL_CARRIERS.filter((c) => c.status === "active").map((carrier) => {
    let speedMultiplier = 1;
    if (speed === "priority") speedMultiplier = 1.4;
    if (speed === "same_day") speedMultiplier = 1.9;

    let base = carrier.baseCost;
    if (!isDomestic && carrier.type === "domestic") {
      base += 60; // Cross-border partner handoff
    }

    const calculatedCost = Math.round((base + (weightKg - 1) * carrier.perKgRate) * speedMultiplier);

    let daysText = `${carrier.slaDaysMin}-${carrier.slaDaysMax} أيام عمل`;
    if (speed === "same_day") daysText = "خلال نفس اليوم (2-6 ساعات)";
    else if (speed === "priority") daysText = `${Math.max(1, carrier.slaDaysMin - 1)}-${carrier.slaDaysMin + 1} أيام عمل`;

    return {
      carrierId: carrier.id,
      carrierName: carrier.nameAr,
      carrierCode: carrier.code,
      logoUrl: carrier.logoUrl,
      costEgp: calculatedCost,
      deliveryEstimateDays: daysText,
      serviceType: carrier.type === "platform_fleet" ? "شحن الأسطول السريع الفوري" : carrier.type === "international" ? "شحن دولي جوي معتمد" : "شحن محلي سريع",
      isFastest: carrier.slaDaysMin <= 1,
      isCheapest: calculatedCost <= 60,
    };
  });
}
